import { test } from 'node:test';
import assert from 'node:assert/strict';
import { checkFindings, lintComment, fingerprint } from '../scripts/lib/findings.mjs';
import { emptyState } from '../scripts/lib/state.mjs';

const review = {
  iteration: { id: 3 },
  files: [
    { path: 'src/app.js', changeType: 'edit', oldContent: 'a\nb\nc\nd\ne\nf\ng\nh\ni\nj\n', newContent: 'a\nB\nc\nd\ne\nf\ng\nh\ni\nj\n', newLineCount: 10, binary: false, tooLarge: false },
    { path: 'src/old.js', changeType: 'delete', oldContent: 'x\n', newContent: null, newLineCount: 0, binary: false, tooLarge: false },
    { path: 'src/cfg.js', changeType: 'add', oldContent: null, newContent: 'const password = "Sandbox123!";\n', newLineCount: 1, binary: false, tooLarge: false },
  ],
};
const ev = { observed: 'x is null when y', trigger: 'call with empty cart', consequence: 'crash' };
const finding = (over = {}) => ({ category: 'Bug', severity: 'High', file: 'src/app.js', line: { start: 2, end: 2 }, title: 'Null cart crashes checkout', evidence: ev, comment: 'This crashes when the cart is empty. Can we guard it?', fix: null, ...over });
const doc = (findings, extra = {}) => ({ story: [], impact: [], licences: [], security: [], checks: [], findings, ...extra });
const run = (findings, state = emptyState(), extra) => checkFindings(review, doc(findings, extra), state);

test('valid doc passes and gets R-01..R-03', () => {
  const r = run([finding(), finding({ title: 'Second', line: { start: 2, end: 3 } }), finding({ file: null, line: null, title: 'No story linked', category: 'Story' })]);
  assert.deepEqual(r.errors, []);
  assert.deepEqual(r.doc.findings.map((f) => f.id), ['R-01', 'R-02', 'R-03']);
  assert.equal(r.state.nextId, 4);
  assert.deepEqual(r.state.findings['R-03'], { title: 'No story linked', file: null });
});

test('unknown category is an error', () => {
  assert.match(run([finding({ category: 'Style' })]).errors.join('\n'), /category/);
});

test('unknown severity is an error', () => {
  assert.match(run([finding({ severity: 'Critical' })]).errors.join('\n'), /severity/);
});

test('line beyond newLineCount is an error', () => {
  assert.match(run([finding({ line: { start: 9, end: 11 } })]).errors.join('\n'), /line/);
});

test('finding on a deleted file is an error', () => {
  assert.match(run([finding({ file: 'src/old.js', line: { start: 1, end: 1 } })]).errors.join('\n'), /deleted/);
});

test('file not in the PR is an error', () => {
  assert.match(run([finding({ file: 'src/nope.js' })]).errors.join('\n'), /not in the PR/);
});

test('file without line is an error', () => {
  assert.match(run([finding({ line: null })]).errors.join('\n'), /line/);
});

test('PR-level finding (file null, line null) is valid', () => {
  assert.deepEqual(run([finding({ file: null, line: null })]).errors, []);
});

test('line outside every changed hunk is a warning only', () => {
  const r = run([finding({ line: { start: 9, end: 9 } })]);
  assert.deepEqual(r.errors, []);
  assert.match(r.warnings.join('\n'), /not near a changed line/);
});

test('missing evidence part is an error', () => {
  assert.match(run([finding({ evidence: { observed: 'x', trigger: '', consequence: 'y' } })]).errors.join('\n'), /evidence\.trigger/);
});

test('fix must be a unified diff', () => {
  assert.match(run([finding({ fix: 'if (cart) {}' })]).errors.join('\n'), /unified diff/);
  assert.deepEqual(run([finding({ fix: '--- a/src/app.js\n+++ b/src/app.js\n@@ -2 +2 @@\n-B\n+b\n' })]).errors, []);
});

test('em dash in comment is an error', () => {
  assert.match(lintComment('This fails \u2014 add a guard', []).join(), /dash/);
});

test('en dash in comment is an error', () => {
  assert.match(lintComment('Lines 3\u20135 fail', []).join(), /dash/);
});

test('attribution in comment is an error', () => {
  for (const t of ['Generated with Claude', 'generated by an AI', 'AI-generated note', 'As an AI, I think', 'Co-Authored-By: x', 'Found by Claude', 'Suggested by ChatGPT']) {
    assert.match(lintComment(t, []).join(), /tool or AI trace/, t);
  }
  assert.deepEqual(lintComment('Plain and clear: add a null check here.', []), []);
});

test('comment repeating a detected secret is an error', () => {
  const r = run([finding({ file: 'src/cfg.js', line: { start: 1, end: 1 }, comment: 'Remove Sandbox123! from the code' })]);
  assert.match(r.errors.join('\n'), /secret/);
  assert.ok(!r.errors.join('\n').includes('Sandbox123!'));
});

test('empty comment is an error', () => {
  assert.match(run([finding({ comment: '  ' })]).errors.join('\n'), /comment/);
});

test('same finding on a second pass keeps its ID', () => {
  const first = run([finding(), finding({ title: 'Other' })]);
  const second = run([finding({ title: 'Other' })], first.state);
  assert.equal(second.doc.findings[0].id, 'R-02');
});

test('given ID that exists in state is kept even when the title changes', () => {
  const first = run([finding()]);
  const second = run([finding({ id: 'R-01', title: 'Reworded title' })], first.state);
  assert.equal(second.doc.findings[0].id, 'R-01');
  assert.equal(second.state.findings['R-01'].title, 'Reworded title');
});

test('new finding on a second pass gets the next ID', () => {
  const first = run([finding()]);
  const second = run([finding(), finding({ title: 'Brand new' })], first.state);
  assert.deepEqual(second.doc.findings.map((f) => f.id), ['R-01', 'R-02']);
});

test('duplicate IDs in one doc are an error', () => {
  const first = run([finding(), finding({ title: 'B' })]);
  assert.match(run([finding({ id: 'R-01' }), finding({ id: 'R-01', title: 'B' })], first.state).errors.join('\n'), /duplicate/i);
});

test('story result outside the enum is an error', () => {
  assert.match(run([], emptyState(), { story: [{ workItemId: 1, criterion: 'x', result: 'done', evidence: 'y' }] }).errors.join('\n'), /story/);
});

test('impact change outside the enum is an error', () => {
  assert.match(run([], emptyState(), { impact: [{ contract: 'OrderDto', path: 'a', change: 'minor', detail: '', consumers: [], deployOrder: '' }] }).errors.join('\n'), /impact/);
});

test('fingerprint ignores case and spaces around the title', () => {
  assert.equal(fingerprint(finding({ title: ' Null cart crashes checkout ' })), fingerprint(finding({ title: 'null cart crashes checkout' })));
});

test('fix repeating a detected secret is an error', () => {
  const r = run([finding({ file: 'src/cfg.js', line: { start: 1, end: 1 }, comment: 'Read it from the environment.', fix: '--- a/src/cfg.js\n+++ b/src/cfg.js\n@@ -1 +1 @@\n-const password = "Sandbox123!";\n+const password = process.env.PW;\n' })]);
  assert.match(r.errors.join('\n'), /fix repeats a secret/);
  assert.ok(!r.errors.join('\n').includes('Sandbox123!'));
});

test('normal comments about claude/ paths or generated code pass', () => {
  assert.deepEqual(lintComment('See claude/managed-settings.json; the client is generated by NSwag.', []), []);
});

test('check records the review iteration', () => {
  assert.equal(run([finding()]).doc.iteration, 3);
});

test('comment or fix carrying a private key is an error', () => {
  assert.match(lintComment('-----BEGIN PRIVATE KEY----- here', []).join(), /private key/);
  const keyReview = { ...review, files: [{ path: 'k.pem', changeType: 'add', oldContent: null, newContent: '-----BEGIN RSA PRIVATE KEY-----\nMIIEowIBAAKCAQEAx1y2z3QwErTyUiOp\n-----END RSA PRIVATE KEY-----\n', newLineCount: 3, binary: false, tooLarge: false }] };
  const r = checkFindings(keyReview, doc([finding({ file: 'k.pem', line: { start: 2, end: 2 }, comment: 'Remove this key.', fix: '--- a/k.pem\n+++ b/k.pem\n@@ -2 +2 @@\n-MIIEowIBAAKCAQEAx1y2z3QwErTyUiOp\n+REDACTED\n' })]), emptyState());
  assert.match(r.errors.join('\n'), /fix repeats a secret/);
});
