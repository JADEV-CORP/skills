// Validates the agent's findings.json against the PR, checks comment wording, and gives
// every finding a stable ID (R-01, R-02, ...) that survives later passes on the same PR.

import { createHash } from 'node:crypto';
import { secretValues } from './secrets.mjs';

export const CATEGORIES = ['Bug', 'Missing', 'Story', 'Breaking change', 'Licence', 'Security', 'Tests', 'Docs', 'Quality'];
export const SEVERITIES = ['Blocker', 'High', 'Medium', 'Low'];
const ENUMS = {
  story: ['result', ['met', 'partly', 'not-met', 'cannot-tell']],
  impact: ['change', ['additive', 'breaking']],
  licences: ['status', ['ok', 'flag', 'unknown']],
  security: ['status', ['ok', 'issue', 'not-applicable']],
  checks: ['result', ['pass', 'fail', 'gap', 'known-failure']],
};
// Attribution phrases only: 'claude/settings.json' or 'generated by NSwag' are normal review text.
const TRACE = /\b(generated|written|created|found|suggested|reviewed) (by|with) (claude|chatgpt|copilot|gemini|an? ai|ai|an? llm)\b|\bai[- ]generated\b|\bas an ai\b|co-authored-by|\u{1F916}/iu;
const NEAR = 3; // lines around a change still count as "on the change"

const text = (v) => typeof v === 'string' && v.trim().length > 0;
const pad = (n) => `R-${String(n).padStart(2, '0')}`;

export function fingerprint(f) {
  return createHash('sha1').update(`${f.category}|${f.file ?? ''}|${String(f.title || '').trim().toLowerCase()}`).digest('hex');
}

const KEY_HEADER = /PRIVATE KEY-----/;
export const fixLeaksSecret = (fix, secrets) => KEY_HEADER.test(String(fix)) || secrets.some((v) => v && String(fix).includes(v));

export function lintComment(comment, secrets) {
  const problems = [];
  if (!text(comment)) return ['comment is empty'];
  if (/[\u2013\u2014]/.test(comment)) problems.push('comment has an en or em dash');
  if (TRACE.test(comment)) problems.push('comment carries a tool or AI trace');
  if (KEY_HEADER.test(comment)) problems.push('comment carries a private key');
  if (secrets.some((s) => s && comment.includes(s))) problems.push('comment repeats a secret found in the diff');
  if (comment.length > 4000) problems.push('comment is longer than 4000 characters');
  return problems;
}

// New-side line numbers that differ from the old side (multiset comparison).
function changedLines(file) {
  const lines = (file.newContent ?? '').split('\n');
  if (file.oldContent == null) return null; // whole file is new
  const old = new Map();
  for (const l of file.oldContent.split('\n')) old.set(l, (old.get(l) || 0) + 1);
  const changed = [];
  lines.forEach((l, i) => {
    if (old.get(l) > 0) old.set(l, old.get(l) - 1);
    else changed.push(i + 1);
  });
  return changed;
}

function checkLocation(f, files, label, errors, warnings) {
  if (f.file == null) {
    if (f.line != null) errors.push(`${label}: line given without a file`);
    return;
  }
  const file = files.get(f.file);
  if (!file) return errors.push(`${label}: file ${f.file} is not in the PR`);
  if (file.changeType === 'delete') return errors.push(`${label}: file ${f.file} is deleted in this PR, comment on the PR instead`);
  const l = f.line;
  if (!l || !Number.isInteger(l.start) || !Number.isInteger(l.end) || l.start < 1 || l.end < l.start) {
    return errors.push(`${label}: line must be { start, end } with 1 <= start <= end`);
  }
  if (file.binary || file.tooLarge) return warnings.push(`${label}: cannot check line ${l.start} in ${f.file} (binary or too large)`);
  if (l.end > file.newLineCount) return errors.push(`${label}: line ${l.end} is past the end of ${f.file} (${file.newLineCount} lines)`);
  const changed = changedLines(file);
  if (changed && !changed.some((c) => c >= l.start - NEAR && c <= l.end + NEAR)) {
    warnings.push(`${label}: line ${l.start} in ${f.file} is not near a changed line`);
  }
}

export function checkFindings(review, doc, state) {
  const errors = [];
  const warnings = [];
  const files = new Map(review.files.map((f) => [f.path, f]));
  const secrets = secretValues(review.files);

  for (const [key, [field, allowed]] of Object.entries(ENUMS)) {
    (doc[key] || []).forEach((item, i) => {
      if (!allowed.includes(item[field])) errors.push(`${key}[${i}].${field} must be one of ${allowed.join(', ')}`);
    });
  }

  const next = { ...state, ids: { ...state.ids }, findings: { ...state.findings } };
  const used = new Set();
  const findings = (doc.findings || []).map((f, i) => {
    const label = `findings[${i}]${f.title ? ` "${f.title}"` : ''}`;
    if (!CATEGORIES.includes(f.category)) errors.push(`${label}: category must be one of ${CATEGORIES.join(', ')}`);
    if (!SEVERITIES.includes(f.severity)) errors.push(`${label}: severity must be one of ${SEVERITIES.join(', ')}`);
    if (!text(f.title)) errors.push(`${label}: title is empty`);
    for (const part of ['observed', 'trigger', 'consequence']) {
      if (!text(f.evidence?.[part])) errors.push(`${label}: evidence.${part} is empty`);
    }
    for (const p of lintComment(f.comment, secrets)) errors.push(`${label}: ${p}`);
    if (f.fix != null && !(/^(--- |diff --git )/m.test(f.fix) && /^@@ /m.test(f.fix))) {
      errors.push(`${label}: fix must be a unified diff (--- a/<file>, +++ b/<file>, @@ hunks)`);
    }
    if (f.fix != null && fixLeaksSecret(f.fix, secrets)) {
      errors.push(`${label}: fix repeats a secret found in the diff; leave fix empty and say in the comment where the value should come from`);
    }
    checkLocation(f, files, label, errors, warnings);

    const fp = fingerprint(f);
    let id = f.id && Object.values(next.ids).includes(f.id) ? f.id : next.ids[fp];
    if (id && used.has(id)) {
      errors.push(`${label}: duplicate ID ${id}`);
    }
    if (!id) {
      id = pad(next.nextId);
      next.nextId += 1;
    }
    used.add(id);
    next.ids[fp] = id;
    next.findings[id] = { title: f.title, file: f.file ?? null };
    return { ...f, id, fix: f.fix ?? null };
  });

  // The iteration lets post refuse findings written for an older push.
  return { errors, warnings, doc: { ...doc, iteration: review.iteration?.id ?? null, findings }, state: next };
}
